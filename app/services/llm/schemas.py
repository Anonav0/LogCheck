"""Strict Pydantic schemas for AI-assisted failure analysis and evidence references."""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class EvidenceReference(BaseModel):
    """Reference to a specific source log line or entity supporting an AI finding."""

    model_config = ConfigDict(extra="forbid")

    line_number: int = Field(
        ...,
        ge=1,
        le=1_000_000,
        description="1-based line number in the original source log",
    )
    excerpt: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Raw or redacted text excerpt from the referenced log line",
    )
    failure_event_id: str | None = Field(
        default=None,
        max_length=100,
        description="Optional failure event ID associated with this evidence",
    )
    fingerprint: str | None = Field(
        default=None,
        max_length=128,
        description="Optional failure fingerprint associated with this evidence",
    )


class LikelyCause(BaseModel):
    """Hypothetical root cause identified by the AI analysis."""

    model_config = ConfigDict(extra="forbid")

    description: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Concise description of the suspected root cause",
    )
    reasoning: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description="Technical justification connecting observed symptoms to this cause",
    )
    evidence_refs: list[EvidenceReference] = Field(
        default_factory=list,
        max_length=50,
        description="Source line references supporting this hypothesis",
    )


class RecommendedAction(BaseModel):
    """Actionable, prioritized debugging or remediation step."""

    model_config = ConfigDict(extra="forbid")

    action: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Specific diagnostic command or investigation action",
    )
    rationale: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description="Explanation of why this action is recommended and what it clarifies",
    )
    priority: Literal["high", "medium", "low"] = Field(
        ...,
        description="Triage priority level for this recommendation",
    )
    evidence_refs: list[EvidenceReference] = Field(
        default_factory=list,
        max_length=50,
        description="Source line references motivating this action",
    )


class AIAnalysis(BaseModel):
    """Structured debugging report generated by an LLM or deterministic fallback."""

    model_config = ConfigDict(extra="forbid")

    summary: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="Executive summary of log health, primary failure patterns, and scope",
    )
    likely_causes: list[LikelyCause] = Field(
        default_factory=list,
        max_length=20,
        description="List of plausible failure causes supported by evidence",
    )
    recommended_actions: list[RecommendedAction] = Field(
        default_factory=list,
        max_length=20,
        description="List of prioritized debugging and triage recommendations",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Assessment confidence score (0.0=pure conjecture, 1.0=conclusive evidence)",
    )
    limitations: list[str] = Field(
        default_factory=list,
        max_length=20,
        description="Explicit caveats, missing telemetry, or information gaps in the log",
    )
    evidence_refs: list[EvidenceReference] = Field(
        default_factory=list,
        max_length=100,
        description="Top-level source evidence references cited across the analysis",
    )


class AIAnalysisResult(BaseModel):
    """Container wrapping the validated AI analysis with operational metadata."""

    analysis: AIAnalysis
    analysis_source: Literal["llm", "fallback"]
    fallback_reason: str | None = None
    provider: str | None = None
    model: str | None = None
    duration_seconds: float = Field(default=0.0, ge=0.0)
    verified_evidence_count: int = Field(default=0, ge=0)
