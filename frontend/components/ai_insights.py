"""AI Insights panel component for LogLens AI dashboard."""

from __future__ import annotations

import streamlit as st


def render_ai_insights(
    ai_analysis: dict | None,
    analysis_source: str = "none",
    status: str = "completed",
    raw_log_lines_count: int = 0,
) -> None:
    """Render the AI insights panel or deterministic fallback report.

    Args:
        ai_analysis: The AIAnalysis dictionary from the response, or None.
        analysis_source: Provenance string: 'llm', 'fallback', or 'none'.
        status: Analysis status string (completed, completed_with_fallback, etc.).
        raw_log_lines_count: Total line count in raw log for reference validation.
    """
    if analysis_source == "none" or ai_analysis is None:
        st.info(
            "ℹ️ **AI Analysis was not requested for this run.**\n\n"
            "To enable AI-assisted debugging triage, select 'Request AI Assistance' before analyzing."
        )
        return

    is_fallback = analysis_source == "fallback" or "fallback" in status.lower()

    if is_fallback:
        st.warning(
            "⚠️ **Deterministic Fallback Analysis Active**\n\n"
            "The insights below were derived deterministically from grouping metrics and error patterns "
            "because the AI provider was disabled, timed out, or encountered verification discrepancies. "
            "These results are strictly heuristic and not generated by an LLM."
        )
    else:
        st.success("🤖 **AI-Assisted Triage Report** (Source: LLM)")

    # Executive Summary
    summary = ai_analysis.get("summary", "")
    if summary:
        st.markdown("### 📋 Executive Summary")
        st.markdown(summary)

    # Confidence and Metadata metrics
    col_conf, col_prov = st.columns([2, 3])
    with col_conf:
        conf = ai_analysis.get("confidence", 0.0)
        conf_pct = int(conf * 100)
        st.metric("Assessment Confidence", f"{conf_pct}%")
        st.progress(conf)
    with col_prov:
        badge_text = "Deterministic Heuristics" if is_fallback else "LLM Generation"
        st.markdown(f"**Analysis Mode:** `{badge_text}`")
        if is_fallback:
            st.caption("Derived from failure recurrence and stack-trace heuristics.")
        else:
            st.caption("Prompt and model outputs validated with source citations.")

    st.markdown("---")

    # Likely Causes
    causes = ai_analysis.get("likely_causes", [])
    if causes:
        st.markdown(f"### 🎯 Likely Root Causes ({len(causes)})")
        for i, cause in enumerate(causes, 1):
            with st.expander(
                f"Cause #{i}: {cause.get('description', 'Untitled Cause')}",
                expanded=i == 1,
            ):
                st.markdown(f"**Technical Reasoning:**\n\n{cause.get('reasoning', '')}")
                cause_refs = cause.get("evidence_refs", [])
                if cause_refs:
                    _render_evidence_selector(
                        cause_refs, f"cause_{i}", raw_log_lines_count
                    )

    # Recommended Actions
    actions = ai_analysis.get("recommended_actions", [])
    if actions:
        st.markdown(f"### 🛠️ Recommended Actions ({len(actions)})")
        priority_colors = {
            "high": "🔴 HIGH",
            "medium": "🟡 MEDIUM",
            "low": "🔵 LOW",
        }
        for j, act in enumerate(actions, 1):
            prio = act.get("priority", "medium").lower()
            badge = priority_colors.get(prio, prio.upper())
            with st.expander(
                f"[{badge}] {act.get('action', 'Investigation Step')}", expanded=j == 1
            ):
                st.markdown(f"**Rationale:**\n\n{act.get('rationale', '')}")
                act_refs = act.get("evidence_refs", [])
                if act_refs:
                    _render_evidence_selector(
                        act_refs, f"action_{j}", raw_log_lines_count
                    )

    # Top-Level Evidence References
    top_refs = ai_analysis.get("evidence_refs", [])
    if top_refs:
        st.markdown("### 🔗 Citations & Evidence References")
        _render_evidence_selector(top_refs, "top_refs", raw_log_lines_count)

    # Limitations & Missing Telemetry
    limitations = ai_analysis.get("limitations", [])
    if limitations:
        with st.expander("⚠️ Caveats & Missing Telemetry", expanded=False):
            for lim in limitations:
                st.markdown(f"- {lim}")


def _render_evidence_selector(
    refs: list[dict],
    key_prefix: str,
    total_lines: int,
) -> None:
    """Render selectable evidence references that trigger source line highlighting."""
    if not refs:
        return

    st.markdown("**Cited Evidence Lines:**")
    for idx, ref in enumerate(refs):
        ln = ref.get("line_number", 0)
        excerpt = ref.get("excerpt", "").strip()
        is_valid = 1 <= ln <= total_lines if total_lines > 0 else True

        col_btn, col_txt = st.columns([1, 4])
        with col_btn:
            btn_label = f"📍 Line {ln}" if is_valid else f"Line {ln} (Out of bounds)"
            if st.button(btn_label, key=f"{key_prefix}_btn_{idx}"):
                st.session_state["_selected_ai_line"] = ln
                st.session_state["source_focus_line"] = ln
                st.rerun()

        with col_txt:
            if excerpt:
                st.code(excerpt, language="text")
